def test_placeholders_become_percent_s_outside_quoted_text():
    sql = "SELECT * FROM t WHERE a = ? AND note = 'why?' AND b LIKE ?"
    assert db.translate_sql(sql, True) == "SELECT * FROM t WHERE a = %s AND note = 'why?' AND b LIKE %s"


def test_percent_signs_are_escaped_only_when_parameters_are_passed():
    assert db.translate_sql("SELECT '100%' WHERE x = ?", True) == "SELECT '100%%' WHERE x = %s"
    assert db.translate_sql("SELECT '100%'", False) == "SELECT '100%'"


def test_create_table_types_become_postgresql_types():
    ddl = db.translate_ddl("CREATE TABLE IF NOT EXISTS t (id INTEGER PRIMARY KEY AUTOINCREMENT, "
                           "unreal_name TEXT, price REAL NOT NULL, at TEXT DEFAULT CURRENT_TIMESTAMP)")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "price DOUBLE PRECISION NOT NULL" in ddl and "unreal_name TEXT" in ddl
    assert "DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')" in ddl
    assert db.translate_ddl("SELECT price REAL FROM t") == "SELECT price REAL FROM t"   # only CREATE TABLE


def test_every_table_is_defined_and_translates_cleanly():
    created = [s for s in db.SCHEMA if s.lstrip().startswith("CREATE TABLE")]
    names = [s.split("EXISTS")[1].split("(")[0].strip() for s in created]
    assert sorted(names) == sorted(db.TABLES)
    for statement in created:
        pg = db.translate_ddl(statement)
        assert "AUTOINCREMENT" not in pg and " REAL" not in pg


def test_numeric_results_come_back_as_ints_or_floats():
    assert db.number_from_text("42") == 42 and isinstance(db.number_from_text("42"), int)
    assert db.number_from_text("-7") == -7
    assert db.number_from_text("3.50") == 3.5 and db.number_from_text("1e3") == 1000.0


def test_rows_read_by_name_position_dict_and_unpacking():
    Row = db.row_class(("sku", "quantity"))
    row = Row(("CARB-1", 5))
    sku, quantity = row
    assert row["sku"] == "CARB-1" and row[1] == 5 and dict(row) == {"sku": "CARB-1", "quantity": 5}
    assert (sku, quantity) == ("CARB-1", 5)


def test_tests_never_use_the_database_from_env():
    os.environ["DATABASE_URL"] = "postgresql://example.invalid/should_not_be_used"
    try:
        with temp_database():
            if not os.environ.get("TEST_DATABASE_URL"):
                assert not db.is_postgres()
            assert db.get_connection().execute("SELECT COUNT(*) FROM products").fetchone()[0] == 0
    finally:
        os.environ.pop("DATABASE_URL", None)


def test_the_new_draft_id_comes_back_on_either_database():
    with temp_database():
        conn = db.get_connection()
        first = db.insert_returning_id(conn, "INSERT INTO draft_listings (sku) VALUES (?)", ("A",))
        second = db.insert_returning_id(conn, "INSERT INTO draft_listings (sku) VALUES (?)", ("B",))
        conn.commit()
        conn.close()
    assert second == first + 1


def test_two_payments_cannot_both_take_the_last_unit():
    with temp_database():
        add_product("LAST-1", stock=1)
        first = checkout.create_session([{"sku": "LAST-1", "quantity": 1}], "a@example.com")
        second = checkout.create_session([{"sku": "LAST-1", "quantity": 1}], "b@example.com")
        paid = checkout.confirm_payment(first["session_id"], "4242424242424242", "12/30", "123")
        late = checkout.confirm_payment(second["session_id"], "4242424242424242", "12/30", "123")
        again = checkout.confirm_payment(first["session_id"], "4242424242424242", "12/30", "123")
        conn = db.get_connection()
        stock = conn.execute("SELECT inventory_qty FROM products WHERE sku = 'LAST-1'").fetchone()[0]
        sales = conn.execute("SELECT COUNT(*) FROM inventory_movements WHERE movement_type = 'sale'").fetchone()[0]
        status = conn.execute("SELECT status FROM orders WHERE session_id = ?", (second["session_id"],)).fetchone()[0]
        conn.close()
    assert paid["status"] == "success"
    assert late["status"] == "error" and "sold out" in late["message"]
    assert again["status"] == "error"
    assert (stock, sales, status) == (0, 1, "pending")
